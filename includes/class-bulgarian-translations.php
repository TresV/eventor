    public function __construct()
    {
        add_filter('gettext', [$this, 'translate'], 20, 3);
        add_filter('ngettext', [$this, 'translate_plural'], 20, 5);
    }

    public function translate(string $translation, string $text, string $domain): string
    {
        if (! $this->should_apply($domain)) {
            return $translation;
        }

        if (isset($this->map[$text])) {
            return $this->map[$text];
        }

        return $translation;
    }

    public function translate_plural(string $translation, string $single, string $plural, int $number, string $domain): string
    {
        if (! $this->should_apply($domain)) {
            return $translation;
        }

        if (1 === $number && isset($this->map[$single])) {
            return $this->map[$single];
        }

        if (1 !== $number && isset($this->map[$plural])) {
            return $this->map[$plural];
        }

        return $translation;
    }

    private function should_apply(string $domain): bool
    {
        if ('Event-Tickets-for-Elementor' !== $domain) {
            return false;
        }

        $locale = function_exists('determine_locale') ? determine_locale() : get_locale();
        return 0 === strpos((string) $locale, 'bg');
    }
